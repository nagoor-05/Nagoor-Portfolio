const profileGithub = "https://github.com/nagoor-05";

const isValidUrl = (value = "") => /^https?:\/\/[^\s#]+$/i.test(String(value).trim());

function project({
  id,
  title,
  statusGroup,
  progress,
  description,
  categories,
  technologies,
  image,
  problem,
  solution,
  features,
  techStack,
  workflow,
  challenges,
  limitations,
  role,
  github = profileGithub,
  live = "",
  star,
  fiveWOneH,
}) {
  const statusLabel = statusGroup === "completed" ? "Completed" : statusGroup === "current" ? "In Progress" : "Upcoming";
  const statusNote = statusGroup === "current" ? "Development in progress" : statusGroup === "upcoming" ? "Planned project" : "";
  const groupedTech = Array.isArray(techStack)
    ? techStack
    : Object.entries(techStack || {}).map(([label, value]) => `${label}: ${value}`);
  const defaultStar = [
    `Situation: ${problem}`,
    `Task: Build ${title} as a practical portfolio project with clear modules, useful workflow, and recruiter-friendly explanation.`,
    `Action: Designed the product flow, selected suitable technologies, implemented the main modules, handled key challenges, and structured the output so the project can be explained clearly in interviews.`,
    `Result: ${solution} The project demonstrates problem solving, system design, implementation thinking, and practical software engineering skills.`,
  ];
  const defaultFiveWOneH = [
    `What: ${title} is ${description.charAt(0).toLowerCase()}${description.slice(1)}`,
    `Why: ${problem}`,
    `Who: It is useful for students, users, recruiters, technical reviewers, and people interested in this project domain.`,
    "Where: It can be applied in academic, personal, business, or operational environments depending on the use case.",
    "When: It is useful when users need faster, clearer, and more organized digital support.",
    `How: ${solution}`,
  ];

  return {
    id,
    title,
    statusGroup,
    statusLabel,
    statusNote,
    progress,
    description,
    categories,
    technologies,
    image,
    github: isValidUrl(github) ? github : "",
    live: isValidUrl(live) ? live : "",
    problem,
    solution,
    features,
    techStack: groupedTech,
    workflow,
    challenges,
    limitations,
    role,
    tags: [...categories.slice(0, 3), ...technologies.slice(0, 4)],
    analysis: {
      star: star || defaultStar,
      fiveWOneH: fiveWOneH || defaultFiveWOneH,
    },
  };
}

