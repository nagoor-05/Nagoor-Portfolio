function enrichProject(project) {
  const tech = project.tags?.length ? project.tags : project.categories || [project.category].filter(Boolean);
  const algorithmSource = project.analysis?.modules?.length
    ? project.analysis.modules
    : project.analysis?.workflow?.length
      ? project.analysis.workflow
      : project.tabs?.workflow || [];
  return {
    ...project,
    tabs: {
      ...project.tabs,
      technology: project.tabs?.technology || tech,
      algorithms: project.tabs?.algorithms || algorithmSource,
    },
  };
}

